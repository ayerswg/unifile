#!/usr/bin/env node
/**
 * One-off generator: GitHub's gemoji list → src/core/emoji-data.js
 *
 * The {document} app's `:shortcode:` emoji completion is fully offline, so the
 * emoji table is committed (like the soundfont and the icons).  Re-run this
 * when the upstream list grows (NETWORK!):
 *
 *   node build/gen-emoji.mjs
 *
 * Source: https://github.com/github/gemoji (MIT) — db/emoji.json.  Each entry
 * carries the glyph, its GitHub shortcodes (`aliases`), a description and
 * search tags.  We keep exactly those four fields, one tab-separated line per
 * emoji, as ONE string literal — smaller than an array of arrays, and parsed
 * lazily on first use (src/core/emoji.js).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SRC = 'https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'core', 'emoji-data.js');

const res = await fetch(SRC);
if (!res.ok) throw new Error(`${SRC}: HTTP ${res.status}`);
const list = await res.json();

const lines = [];
for (const e of list) {
  if (!e.emoji || !e.aliases?.length) continue;
  const clean = s => String(s ?? '').replace(/[\t\n]+/g, ' ').trim();
  lines.push([
    e.emoji,
    e.aliases.map(clean).join(' '),
    clean(e.description),
    (e.tags ?? []).map(clean).join(' '),
  ].join('\t'));
}

const header = `/**
 * GENERATED by build/gen-emoji.mjs from github/gemoji (MIT) — do not edit.
 * One emoji per line: glyph \\t shortcodes \\t description \\t tags
 * ${lines.length} emoji, gemoji db as of ${new Date().toISOString().slice(0, 10)}.
 */
export const EMOJI_TABLE = `;
writeFileSync(OUT, header + JSON.stringify(lines.join('\n')) + ';\n');
console.log(`wrote ${OUT}: ${lines.length} emoji, ${(lines.join('\n').length / 1024).toFixed(0)} KB`);
