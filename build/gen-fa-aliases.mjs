#!/usr/bin/env node
/**
 * One-off generator: Font Awesome's legacy icon names → src/core/fa-aliases.js
 *
 * The {diagram} app bundles the Font Awesome 6 Free icon packs (the
 * @iconify-json/fa6-* dependencies) so mermaid's `fa:fa-user` labels and
 * `@{ icon: "fa:user" }` nodes draw offline.  Those packs carry the CURRENT
 * icon names only, while most diagrams in the wild still use the names Font
 * Awesome 4 and 5 gave them (`fa-edit`, `fa-bank`, `fa-trash-alt`, `fa-close`
 * …).  Font Awesome itself keeps every old name working through its metadata
 * (`icon-families.json` → `aliases.names` for the 5→6 renames, `shims.yml` for
 * the 4→5 ones); this script distils both into one compact `old=new` table.
 *
 * The @fortawesome/fontawesome-free package is NOT a dependency (fonts, css,
 * ~10 MB) — it is fetched into a temp dir for the run (NETWORK!), at the SAME
 * version as the installed @iconify-json/fa6-solid pack so names line up:
 *
 *   node build/gen-fa-aliases.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'core', 'fa-aliases.js');

const version = require('@iconify-json/fa6-solid/info.json').version;
const work = mkdtempSync(path.join(tmpdir(), 'fa-aliases-'));
try {
  execFileSync('npm', ['pack', `@fortawesome/fontawesome-free@${version}`, '--silent'], { cwd: work, stdio: 'inherit' });
  const tgz = readdirSync(work).find(f => f.endsWith('.tgz'));
  execFileSync('tar', ['xzf', tgz, 'package/metadata/icon-families.json', 'package/metadata/shims.yml'], { cwd: work });

  const families = JSON.parse(readFileSync(path.join(work, 'package/metadata/icon-families.json'), 'utf8'));
  const shims = readFileSync(path.join(work, 'package/metadata/shims.yml'), 'utf8');

  // The icons the free packs hold (every family/style the metadata lists as free).
  const free = new Set(Object.entries(families)
    .filter(([, v]) => v.familyStylesByLicense?.free?.length)
    .map(([k]) => k));

  const aliases = new Map();
  const add = (oldName, target) => {
    if (!oldName || oldName === target || free.has(oldName) || !free.has(target)) return;
    if (!aliases.has(oldName)) aliases.set(oldName, target);
  };

  // Font Awesome 5 → 6 renames.
  for (const [name, v] of Object.entries(families)) {
    for (const old of v.aliases?.names ?? []) add(old, name);
  }
  // Font Awesome 4 → 5 shims: `old-name:` blocks with `name:` (and a `prefix:` we
  // don't need — every style lives in the merged sets, see core/fa-icons.js).
  let current = null;
  for (const line of shims.split('\n')) {
    const head = /^([a-z0-9-]+):\s*$/.exec(line);
    if (head) { current = head[1]; continue; }
    const name = /^\s+name:\s*([a-z0-9-]+)\s*$/.exec(line);
    if (name && current) add(current, name[1]);
  }

  const entries = [...aliases].sort(([a], [b]) => a < b ? -1 : 1).map(([o, n]) => `${o}=${n}`);
  // Wrap at ~96 columns: a readable diff when the table changes.
  const lines = [];
  let cur = '';
  for (const e of entries) {
    if (cur && cur.length + e.length + 1 > 96) { lines.push(cur); cur = ''; }
    cur = cur ? `${cur} ${e}` : e;
  }
  if (cur) lines.push(cur);

  const src = `/**
 * Font Awesome legacy icon names — GENERATED by build/gen-fa-aliases.mjs from
 * Font Awesome Free ${version} metadata (CC BY 4.0, © Fonticons, Inc.).
 * Do not edit by hand.
 *
 * \`old=new\` pairs, whitespace-separated: the names Font Awesome 4 and 5 used
 * (\`edit\`, \`bank\`, \`trash-alt\`, \`close\` …) → the Font Awesome 6 icon that
 * replaced them, so a diagram written against any Font Awesome version keeps
 * its icons.  Parsed lazily by src/core/fa-icons.js.
 */
export const FA_ALIASES = \`
${lines.join('\n')}
\`;
`;
  writeFileSync(OUT, src);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${entries.length} aliases from Font Awesome ${version}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
