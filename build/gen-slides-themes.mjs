/**
 * One-off: vendor the three MIT-licensed Marp themes (default / gaia / uncover)
 * from @marp-team/marp-core into src/core/slides/themes.js as plain CSS strings
 * the {slides} app registers with bare Marpit.  Web-font `@import`s are
 * stripped so the themes are fully offline (a system sans/mono is used
 * instead).  marp-core itself is NOT a dependency of the build — install it
 * temporarily to refresh the themes:
 *
 *   npm i --no-save @marp-team/marp-core && node build/gen-slides-themes.mjs
 */

import { writeFile } from 'fs/promises';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const { Marp } = await import('@marp-team/marp-core');
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'core', 'slides', 'themes.js');

const marp = new Marp();
const themes = {};
for (const name of ['default', 'gaia', 'uncover']) {
  themes[name] = marp.themeSet.get(name).css
    .replace(/@import\s+(url\()?["']?https?:[^;]*;\s*/g, '')   // no web fonts: offline
    .replace(/@charset\s+"UTF-8";\s*/g, '');
}

const src = `/**
 * Vendored Marp themes for the {slides} app — GENERATED by
 * build/gen-slides-themes.mjs from @marp-team/marp-core (MIT, © Marp team).
 * Do not edit by hand.  Web-font @imports are stripped (offline).
 */

export const THEMES = ${JSON.stringify(themes, null, 2)};
`;
await writeFile(OUT, src, 'utf8');
console.log(`  ✓ ${OUT}  (${Object.entries(themes).map(([k, v]) => `${k} ${Math.round(v.length / 1024)} KB`).join(', ')})`);
